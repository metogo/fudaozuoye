// Real local API + real configured model; only the starting lesson is synthetic.
import { chromium, expect } from "@playwright/test";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
const require = createRequire(import.meta.url);
const { MockProviderAdapter } = require("../functions/learning-api/dist/lib/learning/providers/adapter.js");
const { getProviderAdapter } = require("../functions/learning-api/dist/lib/learning/providers/index.js");
const { toClientState, openSession, createConsentValue, CONSENT_COOKIE } = require("../functions/learning-api/dist/lib/learning/server-state.js");
const { understandingGate } = require("../functions/learning-api/dist/lib/learning/flow.js");
const mock = new MockProviderAdapter("doubao");
const session = await mock.analyzeProblem(await mock.recognizeProblem("data:image/jpeg;base64,demo"));
const live = getProviderAdapter("doubao", "light");
if (live.mode !== "live") throw new Error("此验证需要已配置的真实模型");
session.modelId = live.modelId; session.mode = live.mode;
session.flow.activeGate = understandingGate(); session.flow.stage = "core_explanation";
const snapshot = { ...toClientState(session), messages: [{ id: "intro", role: "assistant", kind: "assistant", text: "先理解速度与路程之间的关系。", status: "complete", createdAt: new Date().toISOString() }] };
openSession(snapshot.stateToken);
const browser = await chromium.launch({ headless: true, channel: "chrome" });
await mkdir("outputs/knowledge-map-stream", { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await context.addCookies([{ name: CONSENT_COOKIE, value: createConsentValue(), url: "http://localhost:3000" }]);
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.addInitScript(data => sessionStorage.setItem("education-chat-session-v3", JSON.stringify(data)), snapshot);
  await page.goto("http://localhost:3000/");
  const started = Date.now();
  const responsePromise = page.waitForResponse(r => r.url().endsWith("/learning/knowledge-map") && r.request().postDataJSON().stream === true);
  await page.getByRole("button", { name: "本题知识图谱", exact: true }).click();
  await expect(page.getByLabel("可拖拽的知识图谱")).toBeVisible();
  await expect(page.getByRole("timer")).toHaveCount(0);
  const response = await responsePromise;
  if (!response.ok()) throw new Error(`本地图谱接口 ${response.status()}: ${(await response.json()).error?.message}`);
  expect(response.headers()["content-type"]).toContain("text/event-stream");
  const progress = page.getByRole("progressbar");
  await expect(progress).toHaveAttribute("aria-valuenow", /^[1-9]\d*$/, { timeout: 45000 });
  const firstNodeMs = Date.now() - started;
  await page.screenshot({ path: "outputs/knowledge-map-stream/live-progress.png" });
  await expect(page.locator(".knowledge-map-progress")).toContainText(/已全部生成|生成暂时中断/, { timeout: 173000 });
  if (await page.getByText("生成暂时中断", { exact: true }).count()) throw new Error(await page.locator(".knowledge-map-progress").innerText());
  const total = Number(await progress.getAttribute("aria-valuemax"));
  expect(Number(await progress.getAttribute("aria-valuenow"))).toBe(total);
  await expect(page.locator(".react-flow__node")).toHaveCount(total);
  await page.getByRole("button", { name: "查看全图" }).click();
  await page.screenshot({ path: "outputs/knowledge-map-stream/live-complete.png" });
  expect(errors).toEqual([]);
  console.log(JSON.stringify({ passed: true, firstNodeMs, total, elapsedMs: Date.now() - started, transport: "browser → local API → live model → SSE canvas" }));
} finally { await browser.close(); }
