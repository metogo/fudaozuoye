import { chromium, expect } from "@playwright/test";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
const require = createRequire(import.meta.url);
const { MockProviderAdapter } = require("../functions/learning-api/dist/lib/learning/providers/adapter.js");
const { understandingGate } = require("../functions/learning-api/dist/lib/learning/flow.js");
const adapter = new MockProviderAdapter("doubao");
const session = await adapter.analyzeProblem(await adapter.recognizeProblem("data:image/jpeg;base64,demo"));
session.flow.activeGate = understandingGate();
session.flow.stage = "core_explanation";
session.flow.focus = { kind: "problem" };
const original = "甲队每天修35米，乙队每天修25米。\n\n**核对**：两队一天共修60米。";
const snapshot = { session, stateToken: "ui-test-token-".repeat(8), messages: [{ id: "lesson-ui", role: "assistant", kind: "assistant", scopeLabel: "核心思路", text: original, status: "complete", createdAt: new Date().toISOString() }] };
const nodes = ["总量与每天的量", "除法的意义"].map((title, i) => ({ id: `map-${i}`, title, evidence: session.problem.text.slice(0, 200), summary: "", application: "" }));
const edges = [{ from: "map-0", to: "map-1", kind: "prerequisite", reason: "原题中的知识关系保持中文" }];
const plan = { rootId: "map-0", nodes: nodes.map(node => ({ id: node.id, parents: node.id === "map-0" ? [] : ["map-0"] })) };
const frame = (event, data) => `event: ${event}\ndata: ${JSON.stringify(data)}\n\n`;
const browser = await chromium.launch({ channel: "chrome", headless: true });
await mkdir("outputs/ui-language", { recursive: true });
try {
  for (const width of [320, 390, 1280]) {
    const context = await browser.newContext({ viewport: { width, height: 844 }, reducedMotion: "reduce" });
    const page = await context.newPage();
    const errors = [], requests = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("request", request => { if (request.method() === "POST") requests.push(request.url()); });
    await page.route("**/consent", route => route.fulfill({ json: { reasoningLevels: ["light", "medium", "high"].map((id, i) => ({ id, label: ["轻度", "中", "高"][i], available: true })) } }));
    await page.route("**/learning/knowledge-connection", route => route.fulfill({ json: { messageId: "lesson-ui", connection: null } }));
    await page.route("**/learning/knowledge-map", route => route.fulfill({ contentType: "text/event-stream", body: frame("map.plan", { type: "plan", plan }) + nodes.map(node => frame("map.node", { type: "node", node, edges: edges.filter(e => e.to === node.id) })).join("") + frame("complete", { total: 2 }) }));
    await page.goto("http://localhost:3000/");
    await expect(page.getByLabel("从相册选择题目")).toBeEnabled();
    await page.getByRole("textbox", { name: "输入题目或问题" }).fill("保留我的中文题目");
    const before = requests.length;
    await page.getByRole("button", { name: "English interface" }).click();
    await expect(page.getByRole("textbox", { name: "Enter a question" })).toHaveValue("保留我的中文题目");
    await expect(page.getByText("Take a photo", { exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Light", exact: true })).toBeVisible();
    expect(requests.length).toBe(before);
    await page.screenshot({ path: `outputs/ui-language/${width}-home-en.png` });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.reload();
    await expect(page.locator("html")).toHaveAttribute("lang", "en");
    await expect(page.getByText("Take a photo", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Write a question", exact: true }).click();
    await expect(page.getByRole("button", { name: "Read this question" })).toBeVisible();
    await expect(page.getByRole("button", { name: "Pen" })).toBeVisible();
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    await page.evaluate(data => sessionStorage.setItem("education-chat-session-v3", JSON.stringify(data)), snapshot);
    await page.reload();
    await expect(page.getByRole("button", { name: "Full explanation", exact: true })).toBeVisible();
    await expect(page.getByText("甲队每天修35米，乙队每天修25米。", { exact: true })).toBeVisible();
    const storedBefore = await page.evaluate(() => JSON.parse(sessionStorage.getItem("education-chat-session-v3")).messages[0].text);
    await page.screenshot({ path: `outputs/ui-language/${width}-lesson-en.png` });
    const header = page.locator(".chat-header");
    expect(await header.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.getByRole("button", { name: "Knowledge map", exact: true }).click();
    await expect(page.getByText("All concepts ready", { exact: true })).toBeVisible();
    await expect(page.getByText("总量与每天的量", { exact: true })).toBeVisible();
    await expect(page.locator(".react-flow__edge-text")).toHaveText("Understand first");
    await page.screenshot({ path: `outputs/ui-language/${width}-map-en.png` });
    await page.getByRole("button", { name: "Back to conversation" }).click();
    await page.getByRole("button", { name: "中文界面" }).click();
    await expect(page.getByRole("button", { name: "看完整讲解", exact: true })).toBeVisible();
    expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem("education-chat-session-v3")).messages[0].text)).toBe(storedBefore);
    expect(storedBefore).toBe(original);
    expect(errors).toEqual([]);
    console.log(`PASS ${width}px: language switch, refresh, draft/content preserved, no regeneration, whiteboard, graph and edges`);
    await context.close();
  }
} finally { await browser.close(); }
